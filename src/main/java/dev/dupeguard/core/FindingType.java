package dev.dupeguard.core;

/** Тип подозрительной операции. */
public enum FindingType {
    /** За время работы с контейнером суммарное количество предметов выросло. */
    CONTAINER_GAIN("Прирост предметов в контейнере"),
    /** То же, но игрок вышел с сервера с открытым контейнером — классический сценарий дюпа. */
    QUIT_WITH_GAIN("Выход с сервера с приростом предметов"),
    /** Стак больше максимально допустимого размера. */
    OVERSTACK("Переполненный стак"),
    /** Слишком много кликов в инвентаре за секунду (макросы, пакетные эксплойты). */
    CLICK_FLOOD("Флуд кликами в инвентаре"),
    /** Слишком много ценных предметов подобрано за короткое окно времени. */
    PICKUP_BURST("Всплеск подбора ценных предметов");

    private final String title;

    FindingType(String title) {
        this.title = title;
    }

    public String title() {
        return title;
    }
}
